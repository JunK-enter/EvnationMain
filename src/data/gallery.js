export function getGalleryByCategory(categoryId) {
  if (!categoryId || categoryId === 'all') return galleryPhotos
  return galleryPhotos.filter((photo) => photo.categories.includes(categoryId))
}

export function getFeaturedGalleryPhotos(limit = 4) {
  const featured = galleryPhotos.filter((p) => p.featured)
  const rest = galleryPhotos.filter((p) => !p.featured)
  return [...featured, ...rest].slice(0, limit)
}
